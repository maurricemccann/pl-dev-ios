"""Apple's iOS 27 UI-kit tokens -> Shared/AppleTokens.swift (S348, his ask: "complete Apple iOS 27 design token and kits").

The source is the export of Apple's own iOS 27 design library kept in the Design Kit
(C:/dev/pl-design-kit/reference/apple-ios27/apple-ios-27-ui-kit.tokens.json), the same file the R1 apps use.
Only Apple's published values are written, so the generated file is safe in this public repo.
Run: python scripts/apple_tokens.py [path-to-tokens.json]   (re-run when Apple's kit is re-exported)
"""
import json, sys, pathlib, re

SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else r"C:/dev/pl-design-kit/reference/apple-ios27/apple-ios-27-ui-kit.tokens.json")
OUT = pathlib.Path(__file__).resolve().parent.parent / "Shared" / "AppleTokens.swift"
d = json.loads(SRC.read_text(encoding="utf-8"))


def val(node):
    return node.get("$value", node.get("value")) if isinstance(node, dict) else None


def rgba(v):
    if isinstance(v, str):   # a reference like "{Fills.Dark.3 Tertiary}"
        path = v.strip("{}").split(".")
        n = d
        for p in path:
            n = n[p]
        return rgba(val(n))
    r, g, b = v["components"]
    return (round(r, 4), round(g, 4), round(b, 4), round(v.get("alpha", 1), 4))


def ident(name):
    name = re.sub(r"^\d+\s*", "", name)          # "1 Primary" -> "Primary"
    name = re.sub(r"\(.*?\)", "", name)          # "Regular (Default)" -> "Regular"
    parts = re.split(r"[^A-Za-z0-9]+", name)
    s = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return s[:1].lower() + s[1:]


def color(c):
    r, g, b, a = c
    return f"Color(.sRGB, red: {r}, green: {g}, blue: {b}, opacity: {a})"


def dynamic(light, dark):
    return f"IOS27.dyn(light: {color(light)}, dark: {color(dark)})"


out = []
w = out.append
w("// GENERATED by scripts/apple_tokens.py from Apple's iOS 27 UI kit export. Do not edit by hand; re-run the script.")
w("// Native first: where iOS has the real thing (glassEffect, system text styles, List separators, materials) PL DEV uses it;")
w("// these values cover what has no API, and keep custom drawing in step with Apple's kit.")
w("import SwiftUI")
w("import UIKit")
w("")
w("enum IOS27 {")
w("    /// A colour that follows light and dark like Apple's own.")
w("    static func dyn(light: Color, dark: Color) -> Color {")
w("        Color(uiColor: UIColor { $0.userInterfaceStyle == .dark ? UIColor(dark) : UIColor(light) })")
w("    }")
w("")

# simple light/dark colour groups
for group in ["Labels", "Labels - Liquid Glass", "Separators", "Fills", "Grays", "Backgrounds", "Backgrounds Grouped", "System Colors"]:
    g = d[group]
    light = g.get("Light") or g.get("Light")
    dark = g.get("Dark") or g.get("Dark - Base")
    if light is None or dark is None:
        continue
    w(f"    enum {ident(group)[:1].upper() + ident(group)[1:]} {{")
    for k, node in light.items():
        lv, dv = val(node), val(dark.get(k, {})) if isinstance(dark, dict) else None
        if not (isinstance(lv, dict) and isinstance(dv, dict) and "components" in lv and "components" in dv):
            continue
        w(f"        static let {ident(k)} = {dynamic(rgba(lv), rgba(dv))}   // {k}")
    w("    }")
    w("")

# materials: the dark/light fill laid over the blur
w("    /// The tint each material lays over its blur (Thick, Regular, Thin, Ultrathin). Prefer .thickMaterial etc.; this is for custom layers.")
w("    enum MaterialTint {")
for k in d["Materials"]["Light"]:
    lf = val(d["Materials"]["Light"][k]["fills"]["0"]) if "fills" in d["Materials"]["Light"][k] else None
    df = val(d["Materials"]["Dark"][k]["fills"]["0"])
    if lf and df:
        w(f"        static let {ident(k)} = {dynamic(rgba(lf), rgba(df))}   // {k}")
w("    }")
w("")

# Liquid Glass: the first fill (the tint over the lens) and the main shadow, per variant
w("    /// Liquid Glass variants from the kit: the tint fill over the lens and its shadow. The lens itself is .glassEffect().")
w("    struct GlassSpec { let tint: Color; let shadow: Color; let shadowRadius: CGFloat; let shadowX: CGFloat; let shadowY: CGFloat }")
w("    enum Glass {")
lg = d["Liquid Glass"]
for k in lg["Light"]:
    if k not in lg["Dark"]:
        continue
    lfills, dfills = lg["Light"][k].get("fills", {}), lg["Dark"][k].get("fills", {})
    lf, df = val(lfills.get("0", {})), val(dfills.get("0", {}))
    sh = val(lg["Dark"][k].get("shadows", {})) or []
    if not (lf and df):
        continue
    s0 = sh[0] if isinstance(sh, list) and sh else None
    if s0:
        sc = rgba(s0["color"])
        w(f"        static let {ident(k)} = GlassSpec(tint: {dynamic(rgba(lf), rgba(df))}, shadow: {color(sc)}, "
          f"shadowRadius: {s0['blur']['value'] / 2}, shadowX: {s0['offsetX']['value']}, shadowY: {s0['offsetY']['value']})   // {k}")
for k in ["Clear", "Lock Screen Time"]:
    f0 = val(lg[k]["fills"]["0"])
    w(f"        static let {ident(k)}Tint = {color(rgba(f0))}   // {k}")
wg = val(lg["Widget Glass"]["fills"]["0"])
w(f"        static let widget = LinearGradient(colors: [{color(rgba(wg[0]['color']))}, {color(rgba(wg[-1]['color']))}], startPoint: .top, endPoint: .bottom)   // Widget Glass")
w("    }")
w("")

# type: size, weight, leading for normal / tight / loose
w("    /// The type ramp: size in points, weight, and line height as a multiple of size (normal, tight, loose).")
w("    struct TypeSpec { let size: CGFloat; let weight: Int; let leading: Double; let tight: Double; let loose: Double }")
w("    enum TypeRamp {")
for k in [k for k in d if re.match(r"^\d\d ", k)]:
    base = val(d[k]["1 Default"]["text"])
    t = val(d["Tight Leading"][k]["1 Default"]["text"])
    l = val(d["Loose Leading"][k]["1 Default"]["text"])
    w(f"        static let {ident(k)} = TypeSpec(size: {base['fontSize']['value']}, weight: {base['fontWeight']}, "
      f"leading: {round(base['lineHeight'], 4)}, tight: {round(t['lineHeight'], 4)}, loose: {round(l['lineHeight'], 4)})")
w("    }")
w("}")

OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
n = sum(1 for line in out if "static let" in line)
assert n > 60, f"only {n} tokens written; the export's shape changed"
print(f"wrote {OUT} ({n} tokens)")
